-- PatiKitap demo payment history
-- Apply only after review and database backup.
-- This migration does not process real payments.

BEGIN;

CREATE TABLE IF NOT EXISTS patikitap.demo_payment_records (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id INTEGER NOT NULL
        REFERENCES patikitap.transactions(id),
    buyer_id UUID NOT NULL
        REFERENCES patikitap.profiles(id),
    reference VARCHAR(80) NOT NULL UNIQUE,
    method VARCHAR(20) NOT NULL,
    outcome VARCHAR(20) NOT NULL,
    price_cents INTEGER NOT NULL,
    support_cents INTEGER NOT NULL,
    fee_cents INTEGER NOT NULL,
    total_cents INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT demo_payment_method
        CHECK (method IN ('card', 'transfer')),

    CONSTRAINT demo_payment_outcome
        CHECK (outcome IN ('success', 'failed', 'cancelled')),

    CONSTRAINT demo_payment_amounts
        CHECK (
            price_cents > 0
            AND support_cents >= 0
            AND fee_cents >= 0
            AND total_cents = price_cents
            AND support_cents + fee_cents <= price_cents
        )
);

CREATE INDEX IF NOT EXISTS
    ix_demo_payment_records_transaction_id
ON patikitap.demo_payment_records(transaction_id);

CREATE INDEX IF NOT EXISTS
    ix_demo_payment_records_buyer_id
ON patikitap.demo_payment_records(buyer_id);

CREATE UNIQUE INDEX IF NOT EXISTS
    one_successful_demo_payment
ON patikitap.demo_payment_records(transaction_id)
WHERE outcome = 'success';

COMMIT;
